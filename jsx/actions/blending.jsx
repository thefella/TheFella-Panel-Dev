//! Apply effect to highlights using mask and apply image
applyToHighlights = function() {
	if (hasLayerMask() ) {
		targetHighlights();
	} else {
		addLayerMask();
		targetHighlights();
	}
};



//! Apply effect to shadows using mask and apply image
applyToShadows = function() {
	if (hasLayerMask() ) {
		targetShadows();
	} else {
		addLayerMask();
		targetShadows();
	}
};



